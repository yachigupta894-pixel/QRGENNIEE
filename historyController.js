// POST /api/history/scans
// Save a scan. This is what scanner.html calls right after a decode.
// `qrId` is optional — a scanned code doesn't have to be one QR Genie made.
exports.saveScan = async (req, res) => {
  try {
    const { content, type, scannedAt, device, qrId } = req.body;

    if (!content || typeof content !== 'string' || !content.trim()) {
      return res.status(400).json({ message: 'Scan content is required.' });
    }

    const scan = await Scan.create({
      userId: req.user.id,
      qrId: qrId || undefined,
      content: content.trim(),
      type: type || 'Text',
      device: device || req.headers['user-agent'] || 'unknown',
      scannedAt: scannedAt ? new Date(scannedAt) : new Date()
    });

    res.status(201).json({ message: 'Scan saved.', scan });
  } catch (err) {
    console.error('saveScan error:', err);
    res.status(500).json({ message: 'Could not save that scan.' });
  }
};

